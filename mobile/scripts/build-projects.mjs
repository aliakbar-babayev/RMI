// Bundles the demo project documents from ../data into src/projects.ts so the app can offer them
// without a backend endpoint. Run after changing anything in data/:  npm run build:projects
// The text is copied unchanged, so evidence offsets match the original files in data/.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dataDir = join(here, '..', '..', 'data');
const out = join(here, '..', 'src', 'projects.ts');

const SUBTITLE = { P6: 'Core banking engine migration' };
const LANG = { AZ: 'az', RU: 'ru' };

const projects = readdirSync(dataDir)
  .filter((f) => /^P\d+_.+\.md$/.test(f))
  .sort()
  .map((file) => {
    const text = readFileSync(join(dataDir, file), 'utf8');
    const [code, name, suffix] = file.replace(/\.md$/, '').split('_');
    const language = LANG[suffix] ?? 'en';
    const heading = (text.match(/^#\s+(.+)$/m) ?? [, ''])[1];
    const subtitle = SUBTITLE[code] ?? (heading.includes(' - ') ? heading.split(' - ').slice(1).join(' - ').trim() : heading);
    const industry = ((text.match(/(?:Industry|Sahə|Отрасль|Domain):\**\s*([^|\n]+)/) ?? [, ''])[1]).replace(/\*/g, '').trim();
    return { id: suffix ? `${code}-${suffix}` : code, code, name, subtitle, industry, language, source: name, text };
  });

writeFileSync(out, `// Generated by scripts/build-projects.mjs from ../data. Do not edit by hand.
export interface DemoProject {
  id: string; code: string; name: string; subtitle: string; industry: string;
  language: 'en' | 'az' | 'ru'; source: string; text: string;
}

export const PROJECTS: DemoProject[] = ${JSON.stringify(projects, null, 2)};
`);
console.log(`wrote ${projects.length} projects to src/projects.ts:`, projects.map((p) => `${p.id} (${p.language}) ${p.name} - ${p.industry}`).join(' | '));
